// Check MetaMask Connection or fallback to Demo Wallet
async function checkWalletConnection() {
  if (window.ethereum) {
    try {
      const browserProvider = new ethers.BrowserProvider(window.ethereum);
      const accounts = await browserProvider.listAccounts();
      if (accounts.length > 0) {
        state.provider = browserProvider;
        state.userAddress = accounts[0].address;
        state.signer = await browserProvider.getSigner();
        state.walletMode = "metamask";
        updateWalletUI(true);
        return;
      }
    } catch (e) {
      console.warn("MetaMask not connected yet, using demo wallet:", e);
    }
  }
  // Default to built-in Demo Wallet if MetaMask is not installed or not unlocked
  initDemoWallet();
}

// Connect MetaMask
async function connectWallet() {
  if (!window.ethereum) {
    alert("MetaMask is not installed in your browser!\n\nNo problem: NotaryChain has automatically activated the built-in Local Demo Wallet (Account #0 with 10,000 test ETH), so you can notarize and verify documents without downloading any extension!");
    initDemoWallet();
    return;
  }

  try {
    state.provider = new ethers.BrowserProvider(window.ethereum);
    const accounts = await window.ethereum.request({ method: "eth_requestAccounts" });
    if (accounts.length > 0) {
      state.userAddress = accounts[0];
      state.signer = await state.provider.getSigner();
      state.walletMode = "metamask";

      // Check network
      const network = await state.provider.getNetwork();
      state.chainId = Number(network.chainId);

      if (state.chainId !== HARDHAT_CHAIN_ID) {
        await promptSwitchToLocalhost();
      }

      updateWalletUI(true);
    }
  } catch (error) {
    console.error("User denied account access or error:", error);
    alert("Failed to connect MetaMask: " + (error.message || error));
  }
}

// Prompt to switch or add Localhost 31337 network
async function promptSwitchToLocalhost() {
  try {
    await window.ethereum.request({
      method: "wallet_switchEthereumChain",
      params: [{ chainId: HARDHAT_CHAIN_ID_HEX }],
    });
  } catch (switchError) {
    if (switchError.code === 4902) {
      try {
        await window.ethereum.request({
          method: "wallet_addEthereumChain",
          params: [
            {
              chainId: HARDHAT_CHAIN_ID_HEX,
              chainName: "Hardhat Localhost",
              rpcUrls: [HARDHAT_RPC_URL],
              nativeCurrency: {
                name: "ETH",
                symbol: "ETH",
                decimals: 18,
              },
            },
          ],
        });
      } catch (addError) {
        console.error("Failed to add network:", addError);
      }
    }
  }
}

