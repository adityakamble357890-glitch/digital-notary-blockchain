// Load config generated by Hardhat deploy script if available
async function loadContractConfig() {
  try {
    const res = await fetch("./contract-config.json");
    if (res.ok) {
      const config = await res.json();
      if (config.contractAddress) {
        state.contractAddress = config.contractAddress;
        elements.contractAddressInput.value = config.contractAddress;
        localStorage.setItem("notary_contract_address", config.contractAddress);
        console.log("Loaded contract address from config:", config.contractAddress);
      }
    }
  } catch (e) {
    // Silently continue with default address
  }
}

// Event Listeners
