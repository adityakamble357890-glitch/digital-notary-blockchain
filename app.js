// NOTARIZE ACTION
// ==========================================
async function handleNotarizeSubmit() {
  if (!state.notarizeHash) {
    alert("Please select a file first to calculate its SHA-256 hash.");
    return;
  }

  const docName = elements.notarizeDocName.value.trim() || state.notarizeFile?.name || "Document";

  try {
    elements.btnSubmitNotarize.disabled = true;
    elements.notarizeBtnText.innerHTML = `<span class="spinner"></span> Confirming with MetaMask...`;
    showStatus(elements.notarizeStatusAlert, "Please confirm the transaction in MetaMask...", "info");

    const contract = await getContract(true);

    // Pre-check if already notarized to avoid gas waste and revert
    try {
      const [alreadyExists] = await contract.verifyDocument(state.notarizeHash);
      if (alreadyExists) {
        showStatus(elements.notarizeStatusAlert, "⚠️ This document hash has ALREADY been notarized on-chain!", "danger");
        resetNotarizeBtn();
        return;
      }
    } catch (e) {
      // Continue if view call fails
    }

    // Send transaction
    const tx = await contract.notarizeDocument(state.notarizeHash, docName);
    elements.notarizeBtnText.innerHTML = `<span class="spinner"></span> Mining transaction...`;
    showStatus(elements.notarizeStatusAlert, `Transaction broadcast! Waiting for block confirmation... (Tx: ${tx.hash.slice(0, 10)}...)`, "info");

    const receipt = await tx.wait();

    elements.notarizeBtnText.textContent = "Notarize on Blockchain";
    elements.btnSubmitNotarize.disabled = false;

    showStatus(
      elements.notarizeStatusAlert,
      `🎉 Success! Document notarized in block #${receipt.blockNumber}. <a href="javascript:void(0)" onclick="quickVerify('${state.notarizeHash}')" style="color:#6ee7b7; text-decoration:underline; font-weight:bold; margin-left:8px;">Verify it now &rarr;</a>`,
      "success"
    );
  } catch (error) {
    console.error("Notarize error:", error);
    let msg = error.reason || error.message || "Transaction failed";
    if (msg.includes("already notarized")) {
      msg = "This document has already been notarized on the blockchain.";
    } else if (msg.includes("user rejected")) {
      msg = "Transaction rejected by user in MetaMask.";
    }
    showStatus(elements.notarizeStatusAlert, "❌ " + msg, "danger");
    resetNotarizeBtn();
  }
}

function resetNotarizeBtn() {
  elements.btnSubmitNotarize.disabled = false;
  elements.notarizeBtnText.textContent = "Notarize on Blockchain";
}

