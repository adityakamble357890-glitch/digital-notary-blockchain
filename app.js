// Get Read/Write Contract Instance
async function getContract(needSigner = false) {
  const addr = elements.contractAddressInput.value.trim();
  if (!ethers.isAddress(addr)) {
    throw new Error("Invalid Contract Address. Please set it at the top.");
  }

  if (needSigner) {
    if (!state.signer) {
      initDemoWallet();
    }
    return new ethers.Contract(addr, CONTRACT_ABI, state.signer);
  } else {
    // Read-only: Use browser provider or fallback to local JSON-RPC provider
    if (state.provider) {
      return new ethers.Contract(addr, CONTRACT_ABI, state.provider);
    } else {
      const fallbackProvider = new ethers.JsonRpcProvider(HARDHAT_RPC_URL);
      return new ethers.Contract(addr, CONTRACT_ABI, fallbackProvider);
    }
  }
}

