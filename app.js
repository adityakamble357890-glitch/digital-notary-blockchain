// VERIFY ACTION
// ==========================================
async function handleVerifySubmit() {
  const hash = (elements.verifyHashInput.value.trim() || state.verifyHash || "").toLowerCase();

  if (!hash || !hash.startsWith("0x") || hash.length !== 66) {
    alert("Please upload a file or enter a valid 32-byte SHA-256 hash (0x followed by 64 hex characters).");
    return;
  }

  try {
    elements.btnSubmitVerify.disabled = true;
    elements.verifyBtnText.innerHTML = `<span class="spinner"></span> Checking blockchain...`;
    hideResultCards();
    clearAlert(elements.verifyStatusAlert);

    const contract = await getContract(false);
    const [exists, timestamp, docName, notarizedBy] = await contract.verifyDocument(hash);

    elements.btnSubmitVerify.disabled = false;
    elements.verifyBtnText.textContent = "Verify on Blockchain";

    if (exists) {
      // AUTHENTIC DOCUMENT CASE
      elements.resultDocName.textContent = docName || "Untitled Document";
      
      const date = new Date(Number(timestamp) * 1000);
      elements.resultTimestamp.textContent = `${date.toLocaleDateString(undefined, { 
        year: 'numeric', month: 'short', day: 'numeric', hour: '2-digit', minute: '2-digit', second: '2-digit' 
      })} (Unix: ${timestamp.toString()})`;
      
      elements.resultIssuer.textContent = notarizedBy;
      elements.authenticResultCard.classList.add("active");
    } else {
      // UNVERIFIED / MODIFIED DOCUMENT CASE
      elements.resultCheckedHash.textContent = hash;
      elements.unverifiedResultCard.classList.add("active");
    }
  } catch (error) {
    console.error("Verification error:", error);
    elements.btnSubmitVerify.disabled = false;
    elements.verifyBtnText.textContent = "Verify on Blockchain";
    showStatus(
      elements.verifyStatusAlert,
      "Failed to query smart contract: " + (error.reason || error.message || "Ensure Hardhat node is running and contract address is correct."),
      "danger"
    );
  }
}

// UI Helpers
function hideResultCards() {
  elements.authenticResultCard.classList.remove("active");
  elements.unverifiedResultCard.classList.remove("active");
}

function showStatus(el, message, type) {
  el.className = `alert alert-${type} active`;
  el.innerHTML = message;
}

function clearAlert(el) {
  el.className = "alert";
  el.innerHTML = "";
}
